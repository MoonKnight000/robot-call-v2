#!/bin/sh
# POSIX sh — runs as the asterisk-auth-sync init step in docker-compose.yml (busybox ash
# inside curlimages/curl) and by hand in Git Bash.
#
# Writes the three Asterisk credential includes from the environment (.env):
#   ari_auth.conf         [ARI_USER] user for ari.conf          <- ARI_USER, ARI_PASSWORD
#   manager_auth.conf     [AMI_USER] user for manager.conf      <- AMI_USER, AMI_PASSWORD
#   pjsip_local_auth.conf [softphone-auth] + [webtest-auth]     <- SOFTPHONE_PASSWORD, WEB_TEST_SIP_PASSWORD
#
# The committed *.conf files only #include these, so no password is ever tracked in git
# and the same .env drives both Asterisk and the app. A blank value or one still reading
# CHANGE_ME... is refused: the container exits non-zero and `docker compose up` stops
# before Asterisk comes up with a guessable password.
#
# Usage (manual, from the repo root, after `set -a; . ./.env; set +a`):
#   ./asterisk/render-auth.sh
set -eu

DIR="${ASTERISK_CONF_DIR:-$(dirname "$0")/etc/asterisk}"

log() {
    printf '[%s] %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$1"
}

require() {
    name="$1"
    eval "value=\${$name:-}"
    case "$value" in
        '' | CHANGE_ME*)
            log "ERROR: $name is blank or still a CHANGE_ME placeholder — set a real value in .env"
            exit 1
            ;;
    esac
}

require ARI_PASSWORD
require AMI_PASSWORD
require SOFTPHONE_PASSWORD
require WEB_TEST_SIP_PASSWORD

if [ ! -d "$DIR" ]; then
    log "ERROR: $DIR not found"
    exit 1
fi

umask 077
# umask only applies to a new file: an earlier render (another uid, another mode) is
# removed first so the files below always come out owned by this uid, mode 600.
rm -f "$DIR/ari_auth.conf" "$DIR/manager_auth.conf" "$DIR/pjsip_local_auth.conf"

cat > "$DIR/ari_auth.conf" <<EOF
; GENERATED by asterisk/render-auth.sh from .env — do not edit, do not commit.
[${ARI_USER:-robot_call}]
type = user
read_only = no
password = ${ARI_PASSWORD}
EOF

cat > "$DIR/manager_auth.conf" <<EOF
; GENERATED by asterisk/render-auth.sh from .env — do not edit, do not commit.
[${AMI_USER:-uysot-ami}]
secret = ${AMI_PASSWORD}
read = system
write = system
EOF

cat > "$DIR/pjsip_local_auth.conf" <<EOF
; GENERATED by asterisk/render-auth.sh from .env — do not edit, do not commit.
[softphone-auth]
type = auth
auth_type = userpass
username = softphone
password = ${SOFTPHONE_PASSWORD}

[webtest-auth]
type = auth
auth_type = userpass
username = ${WEB_TEST_SIP_USER:-webtest}
password = ${WEB_TEST_SIP_PASSWORD}
EOF

log "wrote ari_auth.conf, manager_auth.conf, pjsip_local_auth.conf in $DIR"
