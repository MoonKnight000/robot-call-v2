package uz.murodjon.robotcallv2.operator.infrastructure.adapter;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Component;
import uz.murodjon.robotcallv2.agent.ami.AmiClient;
import uz.murodjon.robotcallv2.agent.ari.AsteriskProperties;
import uz.murodjon.robotcallv2.operator.application.port.output.OperatorEndpointConfigPort;
import uz.murodjon.robotcallv2.operator.domain.entity.OperatorSipEndpoint;
import uz.murodjon.robotcallv2.operator.infrastructure.config.OperatorProperties;
import uz.murodjon.robotcallv2.siptrunk.infrastructure.config.PjsipConfigProperties;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/**
 * Writes the operators' PJSIP endpoints next to the generated trunk file and reloads
 * res_pjsip over AMI — the same directory and the same switch
 * ({@code voice-agent.siptrunk.*}) as {@code PjsipConfigWriter}, because it is the same
 * Asterisk reading both. pjsip.conf pulls the file in with {@code #tryinclude}.
 *
 * <p>Every endpoint lands in {@code [from-operators]}: the operator's phone can dial a
 * colleague's extension and nothing else. A trunk is reached only through the application,
 * which knows who is dialling and on which company's account — an operator password that
 * leaks is then a way to ring colleagues, not a way to run up a phone bill.
 */
@Component
public class PjsipOperatorEndpointConfigAdapter implements OperatorEndpointConfigPort {

    private static final Logger log = LoggerFactory.getLogger(PjsipOperatorEndpointConfigAdapter.class);
    private static final String HEADER = """
            ; Generated by PjsipOperatorEndpointConfigAdapter — DO NOT EDIT BY HAND.
            ; Rewritten from scratch whenever an operator's SIP account changes.
            ; Included from pjsip.conf with #tryinclude.

            """;

    private final PjsipConfigProperties pjsipConfigProperties;
    private final OperatorProperties operatorProperties;
    private final AmiClient amiClient;
    private final AsteriskProperties asteriskProperties;

    public PjsipOperatorEndpointConfigAdapter(PjsipConfigProperties pjsipConfigProperties,
                                              OperatorProperties operatorProperties, AmiClient amiClient,
                                              AsteriskProperties asteriskProperties) {
        this.pjsipConfigProperties = pjsipConfigProperties;
        this.operatorProperties = operatorProperties;
        this.amiClient = amiClient;
        this.asteriskProperties = asteriskProperties;
    }

    @Override
    public void writeEndpoints(List<OperatorSipEndpoint> endpoints) {
        if (!pjsipConfigProperties.enabled() || pjsipConfigProperties.configDir() == null
                || pjsipConfigProperties.configDir().isBlank()) {
            log.warn("voice-agent.siptrunk.enabled/config-dir not set — {} operator endpoint(s) not written to Asterisk",
                    endpoints.size());
            return;
        }
        Path file = Path.of(pjsipConfigProperties.configDir(), operatorProperties.sipConfigFileName());
        // Phones sign in to the operator cell only; any other cell reaches them over its
        // operator trunk. Written empty rather than skipped, so endpoints left from before
        // the cell was assigned stop accepting registrations.
        List<OperatorSipEndpoint> here = asteriskProperties.isOperatorCell() ? endpoints : List.of();
        try {
            Files.writeString(file, render(here), StandardCharsets.UTF_8);
        } catch (IOException e) {
            log.warn("Could not write {}: {}", file, e.getMessage());
            return;
        }
        boolean reloaded = amiClient.reloadPjsip();
        log.info("Regenerated {} ({} operator endpoint(s)) — Asterisk reload {}", file, here.size(),
                reloaded ? "ok" : "skipped/failed, will retry on next change");
    }

    static String render(List<OperatorSipEndpoint> endpoints) {
        StringBuilder sb = new StringBuilder(HEADER);
        for (OperatorSipEndpoint endpoint : endpoints) {
            String name = endpoint.endpointName();
            sb.append("; --- operator user_id=").append(endpoint.userId())
                    .append(" (company_id=").append(endpoint.companyId()).append(") ---\n");

            sb.append('[').append(name).append("-auth]\n");
            sb.append("type = auth\n");
            sb.append("auth_type = userpass\n");
            sb.append("username = ").append(name).append('\n');
            sb.append("password = ").append(endpoint.password()).append("\n\n");

            sb.append('[').append(name).append("]\n");
            sb.append("type = aor\n");
            sb.append("max_contacts = 3\n");
            sb.append("remove_existing = yes\n");
            sb.append("qualify_frequency = 30\n\n");

            sb.append('[').append(name).append("]\n");
            sb.append("type = endpoint\n");
            sb.append("context = from-operators\n");
            sb.append("disallow = all\n");
            sb.append("allow = ulaw\n");
            sb.append("allow = alaw\n");
            sb.append("direct_media = no\n");
            sb.append("auth = ").append(name).append("-auth\n");
            sb.append("aors = ").append(name).append('\n');
            sb.append("callerid = \"").append(quoteSafe(endpoint.displayName())).append("\" <")
                    .append(endpoint.extension() != null ? endpoint.extension() : name).append(">\n");
            if (endpoint.webrtc()) {
                sb.append("webrtc = yes\n\n");
            } else {
                sb.append("transport = transport-lan\n");
                sb.append("rtp_symmetric = yes\n");
                sb.append("force_rport = yes\n");
                sb.append("rewrite_contact = yes\n\n");
            }
        }
        return sb.toString();
    }

    /** A display name ends up inside a quoted config value; nothing in it may close the quote or the line. */
    private static String quoteSafe(String name) {
        if (name == null) {
            return "";
        }
        return name.replaceAll("[\"\\r\\n;<>]", " ").trim();
    }
}
