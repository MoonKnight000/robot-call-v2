package uz.murodjon.robotcallv2.agent.turn;

import uz.murodjon.robotcallv2.agent.rtp.WavAudio;
import uz.murodjon.robotcallv2.agent.rtp.WavHeader;
import uz.murodjon.robotcallv2.agent.rtp.WavReader;

import java.io.IOException;
import java.nio.ByteBuffer;
import java.nio.ByteOrder;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Random;
import java.util.stream.Stream;

/**
 * Builds the hard callers a turn-taking change has to survive, from clean recordings of
 * single caller utterances, and writes them with a manifest {@link TurnReplayTool} checks.
 *
 * <p><b>Why.</b> A corpus of real calls is mostly easy calls: a quiet room, a caller who
 * says one sentence and stops. The failures are in the rest — the bus stop, the caller who
 * stops halfway to remember a date, the bot's own voice leaking back down the line — and
 * they are too rare to label by hand. Each persona here is the same utterances under one
 * of those conditions, so the expected turn count is known by construction: it is the
 * number of utterances, whatever the condition did to the audio.
 *
 * <ul>
 *   <li>{@code clean} — the utterances with a bot-sized gap between them; the baseline</li>
 *   <li>{@code noisy-snr15}, {@code noisy-snr5} — steady background noise under the speech</li>
 *   <li>{@code hesitation-700}, {@code hesitation-1200} — each utterance split at its
 *       quietest point near the middle by a pause, the caller thinking mid-sentence. The
 *       longer one is above the default post-roll: it fails until a turn detector earns
 *       the extension, which is exactly what it is there to show</li>
 *   <li>{@code bot-echo} — the bot's leaked voice (another utterance, 25 dB down) in every
 *       gap; it must not open a turn of its own</li>
 * </ul>
 *
 * <p>Usage — generate, then replay with the same settings as a live call:
 * <pre>
 *   java -cp ... uz.murodjon.robotcallv2.agent.turn.CallerPersonaAudioTool &lt;clips-dir&gt; &lt;out-dir&gt; [--gap-ms=2500] [--seed=7]
 *   java -cp ... uz.murodjon.robotcallv2.agent.turn.TurnReplayTool &lt;out-dir&gt; --vad-model=... --manifest=&lt;out-dir&gt;/manifest.tsv
 * </pre>
 *
 * <p>The clips must be 8 kHz mono WAV (what the RTP leg carries), one utterance each,
 * trimmed of long leading and trailing silence.
 */
public final class CallerPersonaAudioTool {

    private static final int BOT_ECHO_DB = -25;

    private CallerPersonaAudioTool() {
    }

    public static void main(String[] args) throws IOException {
        if (args.length < 2) {
            System.err.println("Usage: CallerPersonaAudioTool <clips-dir> <out-dir> [--gap-ms=2500] [--seed=7]");
            System.exit(1);
        }
        Path clipsDir = Path.of(args[0]);
        Path outDir = Path.of(args[1]);
        int gapMs = 2500;
        long seed = 7;
        for (String arg : args) {
            if (arg.startsWith("--gap-ms=")) {
                gapMs = Integer.parseInt(arg.substring("--gap-ms=".length()));
            } else if (arg.startsWith("--seed=")) {
                seed = Long.parseLong(arg.substring("--seed=".length()));
            }
        }

        List<short[]> clips = new ArrayList<>();
        int rate = -1;
        try (Stream<Path> paths = Files.list(clipsDir)) {
            for (Path path : paths.filter(p -> p.toString().toLowerCase().endsWith(".wav"))
                    .sorted(Comparator.comparing(Path::toString)).toList()) {
                WavAudio audio = WavReader.read(path);
                if (rate < 0) {
                    rate = audio.sampleRate();
                } else if (rate != audio.sampleRate()) {
                    System.err.printf("Skipping %s: %d Hz, the others are %d Hz%n", path, audio.sampleRate(), rate);
                    continue;
                }
                clips.add(audio.samples());
            }
        }
        if (clips.size() < 2) {
            System.err.println("Need at least two single-utterance clips in " + clipsDir);
            System.exit(1);
        }

        Files.createDirectories(outDir);
        int gap = rate * gapMs / 1000;
        StringBuilder manifest = new StringBuilder("# persona\texpected turns — generated by CallerPersonaAudioTool\n");
        int turns = clips.size();
        write(outDir, "clean", rate, concat(clips, gap, null), turns, manifest);
        write(outDir, "noisy-snr15", rate, addNoise(concat(clips, gap, null), 15, new Random(seed)), turns, manifest);
        write(outDir, "noisy-snr5", rate, addNoise(concat(clips, gap, null), 5, new Random(seed)), turns, manifest);
        write(outDir, "hesitation-700", rate, concat(hesitate(clips, rate, 700), gap, null), turns, manifest);
        write(outDir, "hesitation-1200", rate, concat(hesitate(clips, rate, 1200), gap, null), turns, manifest);
        write(outDir, "bot-echo", rate, concat(clips, gap, scale(clips.get(0), BOT_ECHO_DB)), turns, manifest);
        Files.writeString(outDir.resolve("manifest.tsv"), manifest.toString());
        System.out.printf("Wrote 6 personas of %d utterances to %s%n", turns, outDir);
    }

    private static void write(Path dir, String persona, int rate, short[] pcm, int turns, StringBuilder manifest)
            throws IOException {
        String name = persona + ".wav";
        ByteBuffer data = ByteBuffer.allocate(pcm.length * 2).order(ByteOrder.LITTLE_ENDIAN);
        for (short sample : pcm) {
            data.putShort(sample);
        }
        byte[] header = WavHeader.bytes(rate, 1, pcm.length * 2);
        byte[] bytes = new byte[header.length + pcm.length * 2];
        System.arraycopy(header, 0, bytes, 0, header.length);
        System.arraycopy(data.array(), 0, bytes, header.length, pcm.length * 2);
        Files.write(dir.resolve(name), bytes);
        manifest.append(name).append('\t').append(turns).append('\n');
    }

    /**
     * The utterances one after another, a {@code gap} of line between each and after the
     * last — the time the bot spends answering. {@code leak}, when given, is laid into
     * every gap, as the bot's own voice coming back down the line.
     */
    static short[] concat(List<short[]> clips, int gap, short[] leak) {
        int total = clips.stream().mapToInt(c -> c.length + gap).sum();
        short[] out = new short[total];
        int at = 0;
        for (short[] clip : clips) {
            System.arraycopy(clip, 0, out, at, clip.length);
            at += clip.length;
            if (leak != null) {
                System.arraycopy(leak, 0, out, at, Math.min(leak.length, gap));
            }
            at += gap;
        }
        return out;
    }

    /** Each clip split at its quietest 20 ms between 30 % and 70 % of its length by {@code pauseMs} of silence. */
    static List<short[]> hesitate(List<short[]> clips, int rate, int pauseMs) {
        int frame = rate / 50;
        int pause = rate * pauseMs / 1000;
        List<short[]> out = new ArrayList<>();
        for (short[] clip : clips) {
            int cut = clip.length / 2;
            double quietest = Double.MAX_VALUE;
            for (int start = clip.length * 3 / 10; start + frame <= clip.length * 7 / 10; start += frame) {
                double energy = rms(clip, start, frame);
                if (energy < quietest) {
                    quietest = energy;
                    cut = start + frame / 2;
                }
            }
            short[] split = new short[clip.length + pause];
            System.arraycopy(clip, 0, split, 0, cut);
            System.arraycopy(clip, cut, split, cut + pause, clip.length - cut);
            out.add(split);
        }
        return out;
    }

    /** White noise at {@code snrDb} below the speech's level, measured over the non-silent samples. */
    static short[] addNoise(short[] pcm, double snrDb, Random random) {
        double speechRms = speechRms(pcm);
        double noiseRms = speechRms / Math.pow(10, snrDb / 20);
        short[] out = new short[pcm.length];
        for (int i = 0; i < pcm.length; i++) {
            out[i] = clip(pcm[i] + random.nextGaussian() * noiseRms);
        }
        return out;
    }

    static short[] scale(short[] pcm, double db) {
        double gain = Math.pow(10, db / 20);
        short[] out = new short[pcm.length];
        for (int i = 0; i < pcm.length; i++) {
            out[i] = clip(pcm[i] * gain);
        }
        return out;
    }

    static double speechRms(short[] pcm) {
        double sum = 0;
        int counted = 0;
        for (short sample : pcm) {
            if (Math.abs(sample) > 300) {
                sum += (double) sample * sample;
                counted++;
            }
        }
        return counted == 0 ? 0 : Math.sqrt(sum / counted);
    }

    private static double rms(short[] pcm, int start, int length) {
        double sum = 0;
        for (int i = start; i < start + length; i++) {
            sum += (double) pcm[i] * pcm[i];
        }
        return Math.sqrt(sum / length);
    }

    private static short clip(double value) {
        return (short) Math.max(Short.MIN_VALUE, Math.min(Short.MAX_VALUE, Math.round(value)));
    }
}
